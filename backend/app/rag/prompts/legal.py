# ── 长期记忆提取 ──

MEMORY_EXTRACTION_PROMPT = """你是对话记忆提取专家。

从"用户+助手"的一轮对话中提取**具有长期保存价值**的结构化记忆。
对话格式："用户: ..." 和 "助手: ..."，必须严格区分发言者。

## 两种记忆类型

### 1. user_preference — 用户偏好（宁缺勿滥）

仅提取用户**明确、直接表达**的稳定个人特征。参考真实 AI 产品的偏好提取标准：

✅ 应该提取的（符合以下任一）：
- 语言/输出格式偏好："用英文回答我""以后都用表格呈现数据""回答简短一点"
- 身份/职业背景："我是一名软件工程师""我在国家电网做运维"
- 明确反馈："上次太啰嗦了""术语太多听不懂，讲通俗点"
- 持续主题兴趣："我最近在研究劳动合同纠纷"（而非一次性咨询）

❌ 不应提取的（这些不是偏好）：
- 一次性任务描述："帮我写个快速排序""翻译这段话"
- 知识性问题："变压器的工作原理是什么"
- 助手的回复/寒暄/自我介绍
- 推测或隐含的偏好（用户没说 = 不存在）
- 用户只是提了一个具体案例，并未表达对此主题的持续兴趣

**核心原则**：用户偏好必须来自用户原话，反映跨会话的稳定特征。拿不准就跳过。

### 2. conversation_summary — 对话摘要

记录本轮对话的核心内容：
- 用户问了什么问题、助手给了什么关键结论
- 只记录有"知识沉淀价值"的对话（有实质性问答内容）
- 泛泛寒暄/闲聊/简单问候跳过
- 内容要客观凝练（≤ 50 字），不要把助手回复全文塞进来

注：FAQ 高频模式由系统自动识别（同主题被反复问 3 次以上自动标记），不需要你提取。

## 输出格式

严格 JSON，只有 `items` 一个顶层 key：

```json
{{
  "items": [
    {{
      "type": "user_preference | conversation_summary",
      "content": "≤ 50 字，凝练、完整、自洽",
      "keywords": ["关键词1", "关键词2", "关键词3"],
      "is_new_signal": true
    }}
  ]
}}
```

## 规则
- 没有符合条件的 → `{{"items": []}}`
- 最多 2 条（user_preference 优先于 conversation_summary）
- `keywords`：3~5 个语义关键词
- `content`：不要出现"用户说""助手说"前缀
- `is_new_signal`：本轮新出现的信息为 true

---

用户问题 + 系统回答：
{conversation}"""

